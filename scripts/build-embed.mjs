// Builds dist/squarespace-code-block.html: the whole widget (CSS + deck + JS)
// in one snippet you can paste straight into a Squarespace Code Block, with
// card images and the email endpoint pointing at the deployed site.
//
// Usage: node scripts/build-embed.mjs --site=https://USER.github.io/REPO [--email=https://.../api/send-reading]
//        --site   where site/ is hosted (GitHub Pages, Netlify, ...). Card images load from there.
//        --email  the send-reading endpoint, if one is hosted. Omit it and the email box is hidden.
//        (SITE_URL / EMAIL_ENDPOINT environment variables work too.)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const site = join(root, "site");

const arg = (name) => { const a = process.argv.find((x) => x.startsWith(`--${name}=`)); return a ? a.slice(name.length + 3) : ""; };
const siteUrl = (arg("site") || process.env.SITE_URL || "https://YOUR-WIDGET-URL").replace(/\/+$/, "");
const emailEndpoint = arg("email") || process.env.EMAIL_ENDPOINT || "";

const config = {
  servicesUrl: "https://merlinitemarketing.com/services",
  privacyUrl: "https://merlinitemarketing.com/privacy-policy",
  emailEndpoint,
  cardsBaseUrl: siteUrl + "/cards/",
  imageExt: ".jpg"
};

let css = readFileSync(join(site, "styles.css"), "utf8");
// The page background rule only makes sense on the standalone page.
css = css.replace(/\/\* standalone-only \*\/[\s\S]*?\/\* \/standalone-only \*\//, "");

const deckJs = readFileSync(join(site, "deck.js"), "utf8");
const appJs = readFileSync(join(site, "app.js"), "utf8");

// Never let inlined script content close its own <script> tag early.
const safe = (s) => s.replace(/<\/script/gi, "<\\/script");

const out = `<!--
  Marketing Tarot (inline version). Paste into a Squarespace Code Block (HTML).
  Generated by scripts/build-embed.mjs. Card images load from ${siteUrl}/cards/.
  Email box: ${emailEndpoint ? `posts to ${emailEndpoint} (that server must allow the Squarespace page's origin via ALLOWED_ORIGINS)` : "hidden, no endpoint configured"}.
-->
<div id="marketing-tarot"></div>
<style>
${css.trim()}
</style>
<script>
window.MARKETING_TAROT_CONFIG = ${JSON.stringify(config, null, 2)};
</script>
<script>
${safe(deckJs.trim())}
</script>
<script>
${safe(appJs.trim())}
</script>
`;

mkdirSync(join(root, "dist"), { recursive: true });
const outPath = join(root, "dist", "squarespace-code-block.html");
writeFileSync(outPath, out);
console.log(`wrote ${outPath} (${(out.length / 1024).toFixed(0)} KB, site=${siteUrl}, email=${emailEndpoint || "off"})`);
